pub fn ico(glyph: &'static Icon, size: f32) -> El {
    icon(glyph, size).icon_one_color().color(crate::ui::c(0x62666e))
}

/// One small paper surface for navigation categories and block types. The SVG
/// remains the same Lucide artwork used by the editing controls.
pub fn paper_icon(glyph: &'static Icon, size: f32, tint: u32, theme: crate::model::Theme) -> El {
    use crate::ui::{c, theme_ink};
    rune::el().size(size, size).radius(size * 0.25)
        .fill(c(theme.choose(0xfbfaf7, 0x2b2d32)))
        .border(0.5, c(theme_ink(theme)).alpha(0.12))
        .child(rune::el().absolute(size * 0.15, size * 0.48)
            .size(size * 0.7, size * 0.32).radius(size * 0.12)
            .linear_gradient(0., vec![(0., c(tint).alpha(0.32)), (1., c(tint).alpha(0.12))]).inert())
        .child(rune::el().absolute(0., 0.).size(size, size).center()
            .child(ico(glyph, size * 0.70).color(c(theme_ink(theme)).alpha(0.88))).inert())
        .inert()
}

pub fn category_tint(glyph: &Icon) -> u32 {
    match glyph.name {
        "echo-square-check" | "echo-check" => 0x719b83,
        "echo-lightbulb" | "echo-quote" => 0xc6a35a,
        "echo-code" | "echo-square-terminal" => 0x8b8eaa,
        "echo-image" => 0xb98378,
        "echo-table-2" => 0x6e9ea1,
        _ => 0x8098b1,
    }
}
